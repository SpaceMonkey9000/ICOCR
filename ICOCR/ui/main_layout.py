"""Builds the main window's widgets and layout."""
import sys
from PySide6.QtCore import Qt, QTimer
from PySide6.QtGui import QKeySequence, QShortcut
from PySide6.QtWidgets import (QWidget, QVBoxLayout, QHBoxLayout,
    QPushButton, QLabel, QComboBox, QCheckBox, QPlainTextEdit, QListWidget,
    QTabWidget, QSplitter, QFrame, QToolButton, QSizePolicy, QStatusBar)
from qt_pinout_view import PinoutView
from qt_view import ImageView


class MainLayoutMixin:
    """Widget construction for the main window. Mixed into MainWindow."""

    # -- construction ----------------------------------------------------------
    def _build(self):
        """One workspace: image on the left, findings on the right."""
        self.setMinimumSize(940, 600)
        central = QWidget(self)
        self.setCentralWidget(central)
        outer = QVBoxLayout(central)
        outer.setContentsMargins(10, 10, 10, 7)
        outer.setSpacing(8)

        header = QHBoxLayout()
        header.setSpacing(8)
        title = QLabel('ICOCR')
        title.setObjectName('appTitle')
        header.addWidget(title)
        header.addSpacing(12)
        header.addWidget(QLabel('Camera'))
        self.devices = QComboBox()
        self.devices.setMinimumWidth(140)
        self.devices.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Fixed)
        header.addWidget(self.devices, 1)
        self.start_button = QPushButton('Start')
        self.start_button.clicked.connect(self.start_camera)
        header.addWidget(self.start_button)
        stop = QPushButton('Stop')
        stop.clicked.connect(self.stop_camera)
        header.addWidget(stop)
        open_btn = QPushButton('Open image')
        open_btn.clicked.connect(self.open_image)
        header.addWidget(open_btn)
        folder_btn = QPushButton('Image folder')
        folder_btn.clicked.connect(self.open_image_folder)
        header.addWidget(folder_btn)
        self.settings_button = QPushButton('Settings')
        self.settings_button.clicked.connect(self.open_settings)
        header.addWidget(self.settings_button)
        outer.addLayout(header)

        # Camera mode/back end and the scan flags are edited in Settings; these
        # parentless-in-layout widgets only hold their state.
        self.modes = QComboBox(self)
        self.modes.addItems(['1920x1080 @30', '3840x2160 @30', '1280x720 @30', '640x480 @30'])
        self.backend = QComboBox(self)
        self.backend.addItems(['DirectShow', 'MSMF'] if sys.platform == 'win32' else ['Default'])
        self.live_recognition = QCheckBox('Live recognition', self)
        self.show_all = QCheckBox('Show excluded readings', self)
        self.show_all.toggled.connect(self._populate_readings)
        for hidden in (self.modes, self.backend, self.live_recognition, self.show_all):
            hidden.hide()

        self.workspace = QSplitter(Qt.Orientation.Horizontal)
        self.workspace.setChildrenCollapsible(False)
        self.workspace.setHandleWidth(7)
        outer.addWidget(self.workspace, 1)

        image_panel = QWidget()
        image_panel.setObjectName('cameraWorkspace')
        image_layout = QVBoxLayout(image_panel)
        image_layout.setContentsMargins(0, 0, 0, 0)
        image_layout.setSpacing(5)
        self.view = ImageView()
        self.view.setObjectName('cameraPreview')
        self.view.setMinimumSize(450, 300)
        image_layout.addWidget(self.view, 1)

        controls = QFrame()
        controls.setObjectName('cameraControls')
        controls_layout = QHBoxLayout(controls)
        controls_layout.setContentsMargins(7, 6, 7, 6)
        controls_layout.setSpacing(6)
        self.capture_btn = QPushButton('Capture')
        self.capture_btn.setObjectName('primaryAction')
        self.capture_btn.clicked.connect(self.take_snapshot)
        controls_layout.addWidget(self.capture_btn)
        self.scan_btn = QPushButton('Scan')
        self.scan_btn.setObjectName('primaryAction')
        self.scan_btn.clicked.connect(lambda: self.scan())
        controls_layout.addWidget(self.scan_btn)
        self.freeze_btn = QPushButton('Freeze')
        self.freeze_btn.setCheckable(True)
        self.freeze_btn.toggled.connect(self.set_freeze)
        controls_layout.addWidget(self.freeze_btn)
        self.peaking_btn = QPushButton('Focus peaking')
        self.peaking_btn.setCheckable(True)
        self.peaking_btn.toggled.connect(self.refresh_preview)
        controls_layout.addWidget(self.peaking_btn)
        fit_btn = QPushButton('Fit')
        fit_btn.clicked.connect(self.view.fit_image)
        controls_layout.addWidget(fit_btn)
        for button in (self.capture_btn, self.scan_btn, self.freeze_btn, self.peaking_btn, fit_btn):
            controls_layout.setStretchFactor(button, 1)
            button.setMinimumHeight(34)
        # Buttons must not keep keyboard focus: Space/Enter are global shortcuts.
        for button in (self.capture_btn, self.scan_btn, self.peaking_btn, self.freeze_btn, fit_btn):
            button.setFocusPolicy(Qt.FocusPolicy.NoFocus)
        image_layout.addWidget(controls)
        self.workspace.addWidget(image_panel)

        self.tabs = QTabWidget()
        self.tabs.setObjectName('findingsTabs')
        self.tabs.setMinimumWidth(290)
        identify = QWidget()
        il = QVBoxLayout(identify)
        il.setContentsMargins(10, 10, 10, 10)
        il.setSpacing(7)
        il.addWidget(QLabel('Recognised markings'))
        self.results = QListWidget()
        self.results.setMinimumHeight(110)
        self.results.itemSelectionChanged.connect(self._reading_chosen)
        self.results.itemDoubleClicked.connect(self._choose_reading)
        il.addWidget(self.results, 3)

        # Pinout sits directly below the readings; technical evidence stays in
        # the expandable details panel.
        self.pinout = QWidget()
        pl = QVBoxLayout(self.pinout)
        pl.setContentsMargins(0, 4, 0, 4)
        pl.setSpacing(7)
        self.pinout_title = QLabel('No selected component')
        pl.addWidget(self.pinout_title)
        self.reference_select = QComboBox()
        self.reference_select.activated.connect(self._remember_reference)
        self.reference_select.currentIndexChanged.connect(self._render_reference)
        pl.addWidget(self.reference_select)
        self.pinout_image = PinoutView('No ICDB pinout selected')
        self.pinout_image.setMinimumHeight(200)
        self.pinout_image.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Expanding)
        self.pinout_image.setObjectName('pinoutPreview')
        pl.addWidget(self.pinout_image, 1)
        self.pinout_note = QLabel('Reference is read-only from shared ICDB')
        self.pinout_note.setWordWrap(True)
        pl.addWidget(self.pinout_note)
        self.pinout.setMinimumHeight(230)
        il.addWidget(self.pinout, 5)

        self.datasheet_btn = QPushButton('Search datasheet')
        self.datasheet_btn.setEnabled(False)
        self.datasheet_btn.setToolTip('Search the web for the selected IC part number and datasheet')
        self.datasheet_btn.clicked.connect(self._search_selected_datasheet)
        il.addWidget(self.datasheet_btn)
        self.tabs.addTab(identify, 'Identify')

        history_tab = QWidget()
        hl = QVBoxLayout(history_tab)
        hl.setContentsMargins(10, 10, 10, 10)
        self.history_list = QListWidget()
        self.history_list.currentRowChanged.connect(self._history_selected)
        hl.addWidget(self.history_list, 3)
        self.history_details = QPlainTextEdit()
        self.history_details.setReadOnly(True)
        hl.addWidget(self.history_details, 2)
        self.history_pinout_title = QLabel('Pinout')
        hl.addWidget(self.history_pinout_title)
        self.history_reference_select = QComboBox()
        self.history_reference_select.setToolTip('Choose an ICDB package pinout for this history reading')
        self.history_reference_select.setEnabled(False)
        self.history_reference_select.activated.connect(self._history_reference_chosen)
        hl.addWidget(self.history_reference_select)
        self.history_reference_choices = []
        self.history_pinout_image = PinoutView('Select a history entry to view its pinout')
        self.history_pinout_image.setObjectName('pinoutPreview')
        self.history_pinout_image.setMinimumHeight(150)
        self.history_pinout_image.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Expanding)
        hl.addWidget(self.history_pinout_image, 4)
        self.history_pinout_note = QLabel('')
        self.history_pinout_note.setWordWrap(True)
        hl.addWidget(self.history_pinout_note)
        self._history_pinout_source = None
        history_buttons = QHBoxLayout()
        self.history_datasheet_btn = QPushButton('Search datasheet')
        self.history_datasheet_btn.setEnabled(False)
        self.history_datasheet_btn.clicked.connect(self._search_history_datasheet)
        history_buttons.addWidget(self.history_datasheet_btn)
        self.history_open_icdb_btn = QPushButton('Open in ICDB')
        self.history_open_icdb_btn.setEnabled(False)
        self.history_open_icdb_btn.setToolTip('Open the selected matched component in ICDB')
        self.history_open_icdb_btn.clicked.connect(self._open_history_in_icdb)
        history_buttons.addWidget(self.history_open_icdb_btn)
        self.history_add_icdb_btn = QPushButton('Add to ICDB')
        self.history_add_icdb_btn.setEnabled(False)
        self.history_add_icdb_btn.setToolTip('Stage a new part from this history entry for review in ICDB')
        self.history_add_icdb_btn.clicked.connect(self._add_history_to_icdb)
        history_buttons.addWidget(self.history_add_icdb_btn)
        self.history_alias_btn = QPushButton('Add alias')
        self.history_alias_btn.setEnabled(False)
        self.history_alias_btn.clicked.connect(self._add_history_alias)
        history_buttons.addWidget(self.history_alias_btn)
        history_clear = QPushButton('Clear history')
        history_clear.clicked.connect(self._clear_history)
        history_buttons.addWidget(history_clear)
        hl.addLayout(history_buttons)
        self.history_tab_index = self.tabs.addTab(history_tab, 'History (0)')

        diag_tab = QWidget()
        dl = QVBoxLayout(diag_tab)
        dl.setContentsMargins(10, 10, 10, 10)
        self.diagnostic_text = QPlainTextEdit()
        self.diagnostic_text.setReadOnly(True)
        dl.addWidget(self.diagnostic_text, 2)
        self.diagnostic_tab_index = self.tabs.addTab(diag_tab, 'Diagnostics')
        self.tabs.currentChanged.connect(self._diagnostic_tab_changed)
        self.tabs.currentChanged.connect(lambda _: QTimer.singleShot(0, self._fit_visible_pinouts))

        self.workspace.addWidget(self.tabs)
        self.workspace.setStretchFactor(0, 3)
        self.workspace.setStretchFactor(1, 1)
        self.workspace.setSizes([1050, 440])

        status = QStatusBar(self)
        status.setSizeGripEnabled(False)
        self.setStatusBar(status)
        status.showMessage('Ready — open an image or connect a camera.')

        for keys, action in (('Return', self.scan), ('Enter', self.scan), ('Space', self.take_snapshot),
                             ('F11', self._toggle_fullscreen), ('Escape', self._leave_fullscreen)):
            QShortcut(QKeySequence(keys), self, activated=lambda action=action: action())

