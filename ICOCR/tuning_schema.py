def range_pairs(spec=None):
    """(lower_key, upper_key) settings whose values must satisfy lower <= upper.

    Derived from naming: every '<name>_min' with a matching '<name>_max'
    (e.g. *_height_min/_height_max, ic_tracker.scale_min/scale_max). New keys
    following that convention are covered automatically.
    """
    spec = SPEC if spec is None else spec
    return tuple((key, key[:-4] + '_max') for key in spec
                 if key.endswith('_min') and key[:-4] + '_max' in spec)
